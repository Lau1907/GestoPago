-- Migración V3: Tabla para Registro de Transacciones de Pagos de Servicios (GestoPago)

CREATE TABLE IF NOT EXISTS transacciones_pagos (
    id                          INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_transacciones_pagos PRIMARY KEY,
    idempotency_key             VARCHAR(64)   NOT NULL CONSTRAINT uq_transacciones_idempotency UNIQUE,
    cliente_id                  INTEGER       NOT NULL CONSTRAINT fk_transacciones_cliente REFERENCES clientes(id),
    cuenta_id                   INTEGER       NOT NULL CONSTRAINT fk_transacciones_cuenta REFERENCES cuentas(id),
    numero_cuenta               CHAR(10)      NOT NULL,
    id_producto                 INTEGER       NOT NULL,
    servicio                    VARCHAR(100),
    producto                    VARCHAR(100),
    monto                       NUMERIC(14,2) NOT NULL,
    saldo_anterior              NUMERIC(14,2) NOT NULL,
    saldo_posterior             NUMERIC(14,2),
    referencia_servicio         VARCHAR(50)   NOT NULL,
    digito_verificador          VARCHAR(10),
    estatus                     VARCHAR(20)   NOT NULL,
    codigo_respuesta_gestopago  VARCHAR(10),
    mensaje_respuesta_gestopago VARCHAR(255),
    folio_gestopago             VARCHAR(50),
    autorizacion_gestopago      VARCHAR(50),
    ticket_gestopago            TEXT,
    fecha_creacion              TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion         TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_transacciones_monto CHECK (monto > 0),
    CONSTRAINT ck_transacciones_estatus CHECK (estatus IN ('INICIADA', 'EXITOSA', 'FALLIDA', 'TIMEOUT_REVISION'))
);

CREATE INDEX IF NOT EXISTS ix_transacciones_idempotency ON transacciones_pagos(idempotency_key);
CREATE INDEX IF NOT EXISTS ix_transacciones_cliente_id ON transacciones_pagos(cliente_id);
CREATE INDEX IF NOT EXISTS ix_transacciones_cuenta_id ON transacciones_pagos(cuenta_id);
CREATE INDEX IF NOT EXISTS ix_transacciones_fecha_creacion ON transacciones_pagos(fecha_creacion);
