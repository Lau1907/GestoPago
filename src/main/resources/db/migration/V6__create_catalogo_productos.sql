-- Migración V6: Tabla para persistencia oficial del catálogo de productos GestoPago

CREATE TABLE IF NOT EXISTS catalogo_productos (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_catalogo_productos PRIMARY KEY,
    id_producto            INT           NOT NULL CONSTRAINT uq_catalogo_productos_id_producto UNIQUE,
    id_servicio            INT           NOT NULL,
    servicio               VARCHAR(255)  NOT NULL,
    nombre_producto        VARCHAR(255)  NOT NULL,
    id_cat_tipo_servicio   INT,
    tipo_front             INT,
    has_digito_verificador BOOLEAN       NOT NULL DEFAULT FALSE,
    precio                 VARCHAR(50),
    show_ayuda             BOOLEAN       NOT NULL DEFAULT FALSE,
    tipo_referencia        VARCHAR(50),
    legend                 TEXT,
    url_logo               VARCHAR(255),
    fecha_actualizacion    TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_catalogo_productos_servicio ON catalogo_productos(servicio);
CREATE INDEX IF NOT EXISTS ix_catalogo_productos_id_servicio ON catalogo_productos(id_servicio);
