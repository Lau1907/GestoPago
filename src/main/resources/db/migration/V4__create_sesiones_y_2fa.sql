-- Migración V4: Tablas para Control de Sesión Única y Autenticación de Doble Factor (2FA)

-- 1. Soporte de 2FA en tabla usuarios
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS dos_factores_activo BOOLEAN NOT NULL DEFAULT FALSE;

-- 2. Tabla para Códigos OTP de Autenticación de Doble Factor
CREATE TABLE IF NOT EXISTS codigos_autenticacion (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_codigos_autenticacion PRIMARY KEY,
    usuario_id            INTEGER       NOT NULL CONSTRAINT fk_codigos_autenticacion_usuario REFERENCES usuarios(id),
    codigo                VARCHAR(6)    NOT NULL,
    dispositivo           VARCHAR(20)   NOT NULL DEFAULT 'WEB',
    fecha_creacion        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_expiracion      TIMESTAMP     NOT NULL,
    utilizado             BOOLEAN       NOT NULL DEFAULT FALSE,
    fecha_utilizacion     TIMESTAMP,
    intentos              INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT ck_codigos_autenticacion_codigo_len CHECK (LENGTH(codigo) = 6)
);

CREATE INDEX IF NOT EXISTS ix_codigos_autenticacion_usuario ON codigos_autenticacion(usuario_id);
CREATE INDEX IF NOT EXISTS ix_codigos_autenticacion_utilizado ON codigos_autenticacion(utilizado);
CREATE INDEX IF NOT EXISTS ix_codigos_autenticacion_fecha_exp ON codigos_autenticacion(fecha_expiracion);

-- 3. Tabla para Control de Sesiones Únicas de Usuarios (Web vs Móvil)
CREATE TABLE IF NOT EXISTS sesiones_usuarios (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_sesiones_usuarios PRIMARY KEY,
    usuario_id            INTEGER       NOT NULL CONSTRAINT fk_sesiones_usuarios_usuario REFERENCES usuarios(id),
    token_id              VARCHAR(100)  NOT NULL CONSTRAINT uq_sesiones_token_id UNIQUE,
    dispositivo           VARCHAR(20)   NOT NULL,
    activa                BOOLEAN       NOT NULL DEFAULT TRUE,
    fecha_inicio          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_expiracion      TIMESTAMP     NOT NULL,
    fecha_inactivacion    TIMESTAMP,
    motivo_inactivacion   VARCHAR(150),
    ip_origen             VARCHAR(50),
    user_agent            VARCHAR(255),
    CONSTRAINT ck_sesiones_dispositivo CHECK (dispositivo IN ('WEB', 'MOBILE'))
);

CREATE INDEX IF NOT EXISTS ix_sesiones_usuario_activa ON sesiones_usuarios(usuario_id, activa);
CREATE INDEX IF NOT EXISTS ix_sesiones_token_id ON sesiones_usuarios(token_id);

